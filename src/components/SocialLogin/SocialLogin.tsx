export interface SocialProvider {
  id: string;
  label: string;
  onClick: () => void;
}

export interface SocialLoginProps {
  providers: SocialProvider[];
  /** Show only icon, hide label text */
  iconOnly?: boolean;
  className?: string;
}

export function SocialLogin({ providers, iconOnly = false, className = '' }: SocialLoginProps) {
  return (
    <div className={`${styles.wrap} ${className}`}>
      {providers.map((p) => {
        const iconData = ICONS[p.id];
        return (
          <button
            key={p.id}
            className={styles.btn}
            style={iconData ? { '--brand-color': iconData.color } as React.CSSProperties : undefined}
            onClick={p.onClick}
          >
            {iconData ? (
              <svg
                className={styles.icon}
                viewBox={iconData.viewBox}
                fill="currentColor"
                xmlns="http://www.w3.org/2000/svg"
              >
                <path d={iconData.path} />
              </svg>
            ) : (
              <span className={`${styles.icon} ${styles.fallbackIcon}`}>
                {p.label.charAt(0)}
              </span>
            )}
            {!iconOnly && <span className={styles.label}>{p.label}</span>}
          </button>
        );
      })}
    </div>
  );
}
